//! Streaming readers for the WASM API — the one reader of every format they
//! cover (XYZ, PDB, SDF, LAMMPS data and dump, DCD, XTC, TRR).
//!
//! Implements Phase 1 / Task #4 of the streaming-trajectory spec
//! (see `molvis/docs/specs/streaming-trajectory.md`). The whole-content
//! readers of [`super::reader`] cover only the formats with no stream. These
//! classes are designed to be driven by a worker that owns:
//!
//! - a *reusable* WASM input buffer ([`allocInputBuffer`](
//!   `LAMMPSTrajStream::alloc_input_buffer`)) into which the worker
//!   writes a chunk of the source (e.g. `blob.slice(start, end)`),
//! - a chunk-boundary-safe `FrameIndexBuilder` from `molrs-io` that emits
//!   [`FrameIndexEntry`] records as the source flows through it,
//! - a frame-by-frame parser that decodes a single byte range from the
//!   reusable buffer and returns it as a [`Frame`].
//!
//! Eight wasm classes share this exact shape — `LAMMPSTrajStream`,
//! `XYZStream`, `PDBStream`, `LAMMPSStream`,
//! `SDFStream`, `DCDStream`, `XTCStream`, `TRRStream` —
//! so they are generated by the [`impl_wasm_traj_stream`] macro below.
//! Each only differs in *which* `FrameIndexBuilder` is constructed and
//! *which* `parse_frame_bytes` free function is invoked.
//!
//! # JS lifetime contract
//!
//! The input-buffer pointer returned by
//! [`allocInputBuffer`](`LAMMPSTrajStream::alloc_input_buffer`) lives
//! inside WASM linear memory. `WebAssembly.Memory` may grow on any
//! wasm-bindgen call, which detaches the previous `ArrayBuffer`. Therefore
//! **callers MUST re-derive `new Uint8Array(memory.buffer, ptr, len)`
//! immediately before writing and MUST NOT hold onto the pointer across
//! other wasm calls.** The [`Frame`] a parse returns is an owned handle; the
//! caller frees it.

use molrs::io::streaming::{FrameIndexBuilder, FrameIndexEntry as RsFrameIndexEntry};
use wasm_bindgen::prelude::*;

