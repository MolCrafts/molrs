use molrs::io::trajectory::lammps_dump::{
    LammpsDumpIndexBuilder, parse_frame_bytes as parse_lammps_dump_frame_bytes,
};
use molrs::io::trajectory::trr::{TrrIndexBuilder, parse_frame_bytes as parse_trr_frame_bytes};
