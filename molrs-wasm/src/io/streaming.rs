/// One frame's location inside the source byte stream.
///
/// `byteOffset` is the absolute byte position of the frame's first byte
/// inside the source (round-tripped through `f64`; the spec caps source
/// size at 1 TB which is well within `Number.MAX_SAFE_INTEGER`).
/// `byteLen` is `u32` — per-frame size never exceeds the worker chunk
/// size plus a small slack.
#[wasm_bindgen(js_name = FrameIndexEntry)]
#[derive(Debug, Clone, Copy)]
pub struct FrameIndexEntry {
    byte_offset: f64,
    byte_len: u32,
}

#[wasm_bindgen(js_class = FrameIndexEntry)]
impl FrameIndexEntry {
    /// Absolute byte offset of this frame inside the source (in bytes).
    #[wasm_bindgen(getter, js_name = byteOffset)]
    pub fn byte_offset(&self) -> f64 {
        self.byte_offset
    }

    /// Size of this frame's encoded byte range, in bytes.
    #[wasm_bindgen(getter, js_name = byteLen)]
    pub fn byte_len(&self) -> u32 {
        self.byte_len
    }
}

impl From<RsFrameIndexEntry> for FrameIndexEntry {
    fn from(e: RsFrameIndexEntry) -> Self {
        // `byte_offset: u64 → f64` is exact for values ≤ 2^53; the
        // streaming protocol caps source size at 1 TB.
        Self {
            byte_offset: e.byte_offset as f64,
            byte_len: e.byte_len,
        }
    }
}

// ---------------------------------------------------------------------------
// Macro: generate per-format streaming class
// ---------------------------------------------------------------------------

/// Generate a per-format `*Stream` class.
///
/// Each invocation emits a `#[wasm_bindgen]` struct, a `#[wasm_bindgen]`
/// impl block, and the same set of JS-facing methods. The only thing that
/// varies between formats is the indexer constructor and the
/// `parse_frame_bytes` free function — both passed in as expressions.
macro_rules! impl_wasm_traj_stream {
    (
        struct_name = $struct:ident,
        js_name     = $js:ident,
        new_indexer = $new_indexer:expr,
        parse_fn    = $parse_fn:path,
    ) => {
        #[wasm_bindgen(js_name = $js)]
        pub struct $struct {
            indexer: Option<Box<dyn FrameIndexBuilder>>,
            input_buf: Vec<u8>,
            decoder_ctx: Option<Vec<u8>>,
        }

        #[wasm_bindgen(js_class = $js)]
        impl $struct {
            /// Create a new streaming reader. The reusable input buffer
            /// starts empty; call [`allocInputBuffer`] before feeding data.
            #[wasm_bindgen(constructor)]
            #[allow(clippy::new_without_default)]
            pub fn new() -> Self {
                let indexer: Box<dyn FrameIndexBuilder> = Box::new($new_indexer);
                Self {
                    indexer: Some(indexer),
                    input_buf: Vec::new(),
                    decoder_ctx: None,
                }
            }

            /// Resize the reusable input buffer so it can hold at least
            /// `len` bytes, and return the WASM linear-memory pointer to
            /// its first byte.
            ///
            /// CALLER MUST RE-DERIVE THIS POINTER AFTER ANY OTHER WASM CALL —
            /// `wasm.memory.buffer` may have been detached by a `memory.grow`.
            #[wasm_bindgen(js_name = allocInputBuffer)]
            pub fn alloc_input_buffer(&mut self, len: usize) -> *mut u8 {
                if self.input_buf.len() < len {
                    self.input_buf.resize(len, 0);
                }
                self.input_buf.as_mut_ptr()
            }

            /// Current capacity (in bytes) of the reusable input buffer.
            #[wasm_bindgen(js_name = inputCapacity)]
            pub fn input_capacity(&self) -> usize {
                self.input_buf.len()
            }

            /// Feed the first `len` bytes of the input buffer into the
            /// indexer at absolute source offset `globalOffset`. Returns
            /// any frame entries that became finalized as a result.
            ///
            /// `globalOffset` is round-tripped through `f64`; per the
            /// streaming protocol the source size is capped at 1 TB
            /// (well within `Number.MAX_SAFE_INTEGER`).
            #[wasm_bindgen(js_name = feedIndexChunk)]
            pub fn feed_index_chunk(
                &mut self,
                global_offset: f64,
                len: usize,
            ) -> Result<Vec<FrameIndexEntry>, JsValue> {
                if global_offset < 0.0 || !global_offset.is_finite() {
                    return Err(JsValue::from_str(
                        "feedIndexChunk: globalOffset must be a non-negative finite number",
                    ));
                }
                if len > self.input_buf.len() {
                    return Err(JsValue::from_str(&format!(
                        "feedIndexChunk: len {} exceeds input buffer capacity {}",
                        len,
                        self.input_buf.len()
                    )));
                }
                let indexer = self
                    .indexer
                    .as_mut()
                    .ok_or_else(|| JsValue::from_str("feedIndexChunk: indexer already finished"))?;
                indexer.feed(&self.input_buf[..len], global_offset as u64);
                if let Some(ctx) = indexer.decoder_context() {
                    self.decoder_ctx = Some(ctx);
                }
                Ok(indexer.drain().into_iter().map(Into::into).collect())
            }

            /// Tell the indexer the source length when the host already
            /// knows it (DCD layout probe). No-op for self-describing
            /// formats.
            #[wasm_bindgen(js_name = hintTotalBytes)]
            pub fn hint_total_bytes(&mut self, total: f64) {
                if total < 0.0 || !total.is_finite() {
                    return;
                }
                if let Some(indexer) = self.indexer.as_mut() {
                    indexer.hint_total_bytes(total as u64);
                    if let Some(ctx) = indexer.decoder_context() {
                        self.decoder_ctx = Some(ctx);
                    }
                }
            }

            /// Opaque decoder state (DCD header + optional fixed-atom seed).
            /// Empty when the format is self-describing.
            #[wasm_bindgen(js_name = decoderContext)]
            pub fn decoder_context(&self) -> Option<Vec<u8>> {
                self.decoder_ctx.clone().or_else(|| {
                    self.indexer
                        .as_ref()
                        .and_then(|indexer| indexer.decoder_context())
                })
            }

            /// Install decoder state on a parse-only stream so it can
            /// decode frames while a sibling indexer is still scanning.
            #[wasm_bindgen(js_name = setDecoderContext)]
            pub fn set_decoder_context(&mut self, bytes: Vec<u8>) {
                if !bytes.is_empty() {
                    self.decoder_ctx = Some(bytes);
                }
            }

            /// Signal end-of-stream; return any trailing frame entry. The
            /// indexer is consumed and further `feedIndexChunk` calls
            /// throw.
            #[wasm_bindgen(js_name = finishIndex)]
            pub fn finish_index(&mut self) -> Result<Vec<FrameIndexEntry>, JsValue> {
                // DCD layout may only resolve once the source length is
                // known. Hint with bytes_seen before we consume the
                // indexer so decoder_context is populated for nopbc files.
                if let Some(indexer) = self.indexer.as_mut() {
                    let seen = indexer.bytes_seen();
                    indexer.hint_total_bytes(seen);
                    if let Some(ctx) = indexer.decoder_context() {
                        self.decoder_ctx = Some(ctx);
                    }
                }
                let indexer = self
                    .indexer
                    .take()
                    .ok_or_else(|| JsValue::from_str("finishIndex: indexer already finished"))?;
                let trailing = indexer
                    .finish()
                    .map_err(|e| JsValue::from_str(&format!("finishIndex: {}", e)))?;
                Ok(trailing.into_iter().map(Into::into).collect())
            }

            /// Decode the byte range `[offset, offset + len)` from the
            /// reusable input buffer as a single frame and return it.
            ///
            /// The returned [`Frame`] owns its data (the caller frees it);
            /// the input buffer may be overwritten as soon as this returns.
            #[wasm_bindgen(js_name = parseRangeInInput)]
            pub fn parse_range_in_input(
                &mut self,
                offset: usize,
                len: usize,
            ) -> Result<Frame, JsValue> {
                let end = offset.checked_add(len).ok_or_else(|| {
                    JsValue::from_str("parseRangeInInput: offset + len overflowed usize")
                })?;
                if end > self.input_buf.len() {
                    return Err(JsValue::from_str(&format!(
                        "parseRangeInInput: range {}..{} exceeds input buffer length {}",
                        offset,
                        end,
                        self.input_buf.len()
                    )));
                }
                let bytes = &self.input_buf[offset..end];
                // DCD is the only format whose `parse_fn` consults decoder
                // context. Other formats ignore it so a stray
                // `setDecoderContext` cannot wrap XTC/TRR bytes in DCD magic
                // (and never copies the frame just to prepend a prefix).
                let frame = $parse_fn(bytes, self.decoder_ctx.as_deref())
                    .map_err(|e| JsValue::from_str(&format!("parse error: {}", e)))?;
                Frame::from_rs(frame)
            }
        }
    };
}

