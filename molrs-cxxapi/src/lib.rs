// ── Element lookup ───────────────────────────────────────────────────────────

/// Symbol for the FFI-shared [`bridge::ffi::Element`] — panics on an invalid
/// value (no fallback).
fn element_symbol(e: bridge::ffi::Element) -> &'static str {
    Element::by_number(e.repr)
        .unwrap_or_else(|| panic!("element_symbol: invalid Element value {}", e.repr))
        .symbol()
}

fn symbol_for_z(z: i32) -> &'static str {
    let element = u8::try_from(z)
        .ok()
        .and_then(Element::by_number)
        .unwrap_or_else(|| panic!("symbol_for_z: invalid atomic number {z}"));
    element.symbol()
}

// ── Frame builders (raw C++ arrays → transient molrs Frame) ─────────────────
//
// The C++ engine measures; molrs analyzes/stores. Each FFI call below builds a
// throwaway `Frame` from the caller's flat buffers — there is no persistent
// C++-side accumulator (the old staging shells are gone).

/// Build a bare frame carrying only `atoms.{x,y,z}` (+ optional simbox).
///
/// Used by the analysis kernels, which read positions via `FrameAccess`.
fn xyz_frame(x: Vec<f64>, y: Vec<f64>, z: Vec<f64>, box_mat: Option<&[f64]>) -> Frame {
    let mut atoms = Block::new();
    atoms.insert("x", Array1::from_vec(x).into_dyn()).unwrap();
    atoms.insert("y", Array1::from_vec(y).into_dyn()).unwrap();
    atoms.insert("z", Array1::from_vec(z).into_dyn()).unwrap();
    let mut frame = Frame::new();
    frame.insert("atoms", atoms);
    if let Some(bm) = box_mat
        && bm.len() >= 9
    {
        let h = Array2::from_shape_vec((3, 3), bm[..9].to_vec()).unwrap();
        if let Ok(sb) = SimBox::new(h, Array1::zeros(3), [true, true, true]) {
            frame.simbox = Some(sb);
        }
    }
    frame
}

/// Build a frame with `atoms.{element,x,y,z}` (+ simbox) for XYZ/Zarr writing.
///
/// `element` is derived from the atomic number `type_id` via [`symbol_for_z`].
fn frame_with_elements(type_id: &[i32], x: &[f64], y: &[f64], z: &[f64], box_mat: &[f64]) -> Frame {
    let n = type_id.len();
    let symbols: Vec<String> = type_id
        .iter()
        .map(|&z| symbol_for_z(z).to_string())
        .collect();
    let mut atoms = Block::new();
    atoms
        .insert(
            "element",
            Array1::from_vec(symbols).into_dyn() as ArrayD<String>,
        )
        .unwrap();
    atoms
        .insert("x", Array1::from_vec(x[..n].to_vec()).into_dyn())
        .unwrap();
    atoms
        .insert("y", Array1::from_vec(y[..n].to_vec()).into_dyn())
        .unwrap();
    atoms
        .insert("z", Array1::from_vec(z[..n].to_vec()).into_dyn())
        .unwrap();
    let mut frame = Frame::new();
    frame.insert("atoms", atoms);
    if box_mat.len() >= 9 {
        let h = Array2::from_shape_vec((3, 3), box_mat[..9].to_vec()).unwrap();
        if let Ok(sb) = SimBox::new(h, Array1::zeros(3), [true, true, true]) {
            frame.simbox = Some(sb);
        }
    }
    frame
}

// ── Trajectory-analysis compute objects (mirror molrs::compute::*) ────────────
//
// molrs's own calling convention, bridged as CXX opaque types: instantiate a
// compute with its config (`*_compute_new`), then call `compute(...)` over the
// whole accumulated raw trajectory. One-shot and stateless — matching the molrs
// `Compute` trait, there is no frame-by-frame accumulator. Each `compute`
// rebuilds transient molrs frames from the flat buffers and delegates the math
// to molrs (`compute::*`); no analysis math lives here. The engine measures;
// molrs analyzes.

/// Mean squared displacement compute — see [`MsdCompute::compute`].
pub struct MsdCompute;

/// Construct an MSD compute (Direct mode: first frame = reference).
fn msd_compute_new() -> Box<MsdCompute> {
    Box::new(MsdCompute)
}

impl MsdCompute {
    /// `MSD(t)` over a raw `[n_frames, n_dof]` position buffer.
    ///
    /// `positions` is row-major with each frame blocked `x[0..na) y[..) z[..)`
    /// (`na = n_dof/3`). `MsdMode::Direct` — `MSD(t) = ⟨|r(t) − r(0)|²⟩_i` with
    /// the first frame as reference (LAMMPS `compute msd`). All math is molrs
    /// (`compute::MSD`). Returns one mean value per frame (index 0 = 0); empty on
    /// < 2 frames or a bad shape — never panics.
    pub fn compute(&self, positions: &[f64], n_frames: i64, n_dof: i64) -> Vec<f64> {
        use molrs::compute::{Compute, MSD};
        if n_frames < 2 || n_dof < 3 || n_dof % 3 != 0 {
            return Vec::new();
        }
        let (nf, nd) = (n_frames as usize, n_dof as usize);
        if positions.len() != nf * nd {
            return Vec::new();
        }
        let na = nd / 3;
        let frames: Vec<Frame> = (0..nf)
            .map(|t| {
                let b = t * nd;
                xyz_frame(
                    positions[b..b + na].to_vec(),
                    positions[b + na..b + 2 * na].to_vec(),
                    positions[b + 2 * na..b + 3 * na].to_vec(),
                    None,
                )
            })
            .collect();
        let refs: Vec<&Frame> = frames.iter().collect();
        match MSD::new().compute(&refs, ()) {
            Ok(ts) => ts.data.iter().map(|r| r.mean).collect(),
            Err(_) => Vec::new(),
        }
    }
}

/// Einstein self-diffusion compute — see [`DiffusionCompute::compute`].
pub struct DiffusionCompute {
    dt: f64,
    dims: i32,
    fit_lo: f64,
    fit_hi: f64,
}

/// Construct an Einstein-diffusion compute. `dt` = time between frames; `dims` =
/// spatial dimensionality; `[fit_lo, fit_hi]` = the MSD-slope fit window.
fn diffusion_compute_new(dt: f64, dims: i32, fit_lo: f64, fit_hi: f64) -> Box<DiffusionCompute> {
    Box::new(DiffusionCompute {
        dt,
        dims,
        fit_lo,
        fit_hi,
    })
}

impl DiffusionCompute {
    /// `D = slope / (2*dims)` from the windowed-MSD slope over `[fit_lo, fit_hi]`
    /// (fractions of the last lag), over a raw `[n_frames, n_dof]` position
    /// buffer (same layout as [`MsdCompute::compute`]). All math is molrs
    /// (`EinsteinDiffusion` + `LinearFit`). Returns `NaN` on < 2 frames, a bad
    /// shape/args, or a fit error — never panics.
    pub fn compute(&self, positions: &[f64], n_frames: i64, n_dof: i64) -> f64 {
        use molrs::compute::{Compute, EinsteinDiffusion, EinsteinDiffusionArgs, Fit, LinearFit};
        if n_frames < 2
            || n_dof < 3
            || n_dof % 3 != 0
            || self.dt <= 0.0
            || self.dt.is_nan()
            || self.dims <= 0
        {
            return f64::NAN;
        }
        let (nf, nd) = (n_frames as usize, n_dof as usize);
        if positions.len() != nf * nd {
            return f64::NAN;
        }
        let na = nd / 3;
        let frames: Vec<Frame> = (0..nf)
            .map(|t| {
                let b = t * nd;
                xyz_frame(
                    positions[b..b + na].to_vec(),
                    positions[b + na..b + 2 * na].to_vec(),
                    positions[b + 2 * na..b + 3 * na].to_vec(),
                    None,
                )
            })
            .collect();
        let refs: Vec<&Frame> = frames.iter().collect();
        let ed = match EinsteinDiffusion.compute(&refs, EinsteinDiffusionArgs { dt: self.dt }) {
            Ok(r) => r,
            Err(_) => return f64::NAN,
        };
        match (LinearFit {
            window: (self.fit_lo, self.fit_hi),
        })
        .fit((&ed.lag_times, &ed.msd))
        {
            Ok(fit) => fit.slope / (2.0 * self.dims as f64),
            Err(_) => f64::NAN,
        }
    }
}

/// Velocity autocorrelation compute — see [`VacfCompute::compute`].
pub struct VacfCompute {
    dt: f64,
    resolution: i64,
}

/// Construct a VACF compute. `dt` = time between frames; `resolution` caps the
/// max lag.
fn vacf_compute_new(dt: f64, resolution: i64) -> Box<VacfCompute> {
    Box::new(VacfCompute { dt, resolution })
}

impl VacfCompute {
    /// DOF-averaged VACF over a row-major `[n_frames, n_dof]` velocity buffer.
    /// All math is molrs (`compute::VACF`, FFT-ACF). Returns the VACF curve (one
    /// value per lag, index 0 = zero lag); empty on fewer than two frames, a
    /// shape/arg error, or a compute error.
    pub fn compute(&self, velocities: &[f64], n_frames: i64, n_dof: i64) -> Vec<f64> {
        use molrs::compute::{Compute, VACF};
        if n_frames < 2 || n_dof < 1 || self.dt <= 0.0 || self.dt.is_nan() || self.resolution < 1 {
            return Vec::new();
        }
        let (nf, nd) = (n_frames as usize, n_dof as usize);
        if velocities.len() != nf * nd {
            return Vec::new();
        }
        let vel = match Array2::from_shape_vec((nf, nd), velocities.to_vec()) {
            Ok(a) => a,
            Err(_) => return Vec::new(),
        };
        let frames: &[&Frame] = &[]; // VACF ignores the frame slice; velocities are in args
        match VACF.compute(frames, (&vel, self.dt, self.resolution as usize)) {
            Ok(r) => r.acf.to_vec(),
            Err(_) => Vec::new(),
        }
    }
}

/// Radial distribution function compute — see [`RdfCompute::compute`].
pub struct RdfCompute {
    n_bins: i64,
    r_max: f64,
    r_min: f64,
}

/// Construct an RDF compute. `n_bins`, `r_max`, `r_min` (Å) — argument order
/// mirrors molrs `RDF::new(n_bins, r_max, r_min)`.
fn rdf_compute_new(n_bins: i64, r_max: f64, r_min: f64) -> Box<RdfCompute> {
    Box::new(RdfCompute {
        n_bins,
        r_max,
        r_min,
    })
}

impl RdfCompute {
    /// g(r) over raw `[n_frames, 3*n_atoms]` positions (blocked `x|y|z` per
    /// frame) + `[n_frames, 9]` per-frame cell matrices.
    ///
    /// Per frame: rebuild a transient `Frame` (x/y/z + `SimBox` from the 9 cell
    /// values, periodic) and a `LinkCell` self-neighbor list (cutoff `r_max`),
    /// then `compute::RDF` batch-accumulates pair distances into `n_bins` bins
    /// over `[r_min, r_max]` (Å), normalized by the ideal-gas shell volume at
    /// each frame's number density. The per-frame `boxes` support NPT. The
    /// caller derives bin-center radii. Returns an empty vector on bad
    /// args/shape, a missing `SimBox`, or a compute error — never panics.
    pub fn compute(
        &self,
        positions: &[f64],
        boxes: &[f64],
        n_frames: i64,
        n_atoms: i64,
    ) -> Vec<f64> {
        use molrs::compute::RDF;
        if n_frames < 1
            || n_atoms < 1
            || self.n_bins < 1
            || self.r_max <= 0.0
            || self.r_max.is_nan()
            || self.r_min < 0.0
            || self.r_min >= self.r_max
        {
            return Vec::new();
        }
        let (nf, na) = (n_frames as usize, n_atoms as usize);
        let nd = na * 3;
        if positions.len() != nf * nd || boxes.len() != nf * 9 {
            return Vec::new();
        }
        // Stream frame-by-frame through the core accumulator (one transient
        // frame + LinkCell at a time — the batch buffer is never duplicated).
        let rdf = match RDF::new(self.n_bins as usize, self.r_max, self.r_min) {
            Ok(r) => r,
            Err(_) => return Vec::new(),
        };
        let mut acc = RDFAccumulatorCore::new(rdf);
        for t in 0..nf {
            let b = t * nd;
            let Some((frame, nlist)) =
                frame_and_self_nlist(&positions[b..b + nd], &boxes[t * 9..t * 9 + 9], self.r_max)
            else {
                return Vec::new();
            };
            if acc.accumulate(&frame, &nlist).is_err() {
                return Vec::new();
            }
        }
        match acc.finalize() {
            Ok(res) => res.rdf.to_vec(),
            Err(_) => Vec::new(),
        }
    }
}

// ── Streaming trajectory-analysis accumulators ───────────────────────────────
// Bounded-memory counterparts of the one-shot computes above. The engine feeds
// one frame per call; molrs owns every piece of analysis math. See the bridge
// schema (build.rs) for the C++-visible contracts.

/// Build one transient molrs frame + `LinkCell` self-neighbor list from a flat
/// blocked `x|y|z` position frame and a row-major 3×3 cell.
///
/// Shared by the batch [`RdfCompute`] and the streaming [`RdfAccumulator`] —
/// one marshaling path for both. `None` on an empty / non-multiple-of-3
/// position slice, a malformed cell, or a rejected `SimBox`.
fn frame_and_self_nlist(
    positions: &[f64],
    box9: &[f64],
    r_max: f64,
) -> Option<(Frame, molrs::spatial::neighbors::NeighborList)> {
    use molrs::spatial::neighbors::{LinkCell, NbListAlgo};
    if positions.is_empty() || !positions.len().is_multiple_of(3) || box9.len() != 9 {
        return None;
    }
    let na = positions.len() / 3;
    let frame = xyz_frame(
        positions[0..na].to_vec(),
        positions[na..2 * na].to_vec(),
        positions[2 * na..3 * na].to_vec(),
        Some(box9),
    );
    let mut pos = Array2::<F>::zeros((na, 3));
    for a in 0..na {
        pos[[a, 0]] = positions[a];
        pos[[a, 1]] = positions[na + a];
        pos[[a, 2]] = positions[2 * na + a];
    }
    let nlist = {
        let simbox = frame.simbox.as_ref()?;
        let mut lc = LinkCell::new().cutoff(r_max);
        lc.build(pos.view(), simbox);
        lc.query().clone()
    };
    Some((frame, nlist))
}

use molrs::compute::RDFAccumulator as RDFAccumulatorCore;

/// Streaming g(r) accumulator — wraps molrs `compute::RDFAccumulator`
/// (O(n_bins) state). Invalid construction parameters leave it inert: every
/// `accumulate` returns `false` and `finalize` returns empty.
pub struct RdfAccumulator {
    r_max: f64,
    inner: Option<RDFAccumulatorCore>,
}

/// Construct a streaming RDF accumulator. `n_bins`, `r_max`, `r_min` (Å) —
/// same argument order as [`rdf_compute_new`].
fn rdf_accumulator_new(n_bins: i64, r_max: f64, r_min: f64) -> Box<RdfAccumulator> {
    use molrs::compute::RDF;
    let inner = if n_bins >= 1 {
        RDF::new(n_bins as usize, r_max, r_min)
            .ok()
            .map(RDFAccumulatorCore::new)
    } else {
        None
    };
    Box::new(RdfAccumulator { r_max, inner })
}

impl RdfAccumulator {
    /// Fold one frame (blocked `x|y|z` positions + row-major 3×3 cell) into
    /// the running histogram. `false` when the frame is rejected (bad shape,
    /// missing/degenerate box) — state is unchanged in that case.
    pub fn accumulate(&mut self, positions: &[f64], box9: &[f64]) -> bool {
        let Some(acc) = self.inner.as_mut() else {
            return false;
        };
        let Some((frame, nlist)) = frame_and_self_nlist(positions, box9, self.r_max) else {
            return false;
        };
        acc.accumulate(&frame, &nlist).is_ok()
    }

    /// Number of accepted frames.
    pub fn n_frames(&self) -> i64 {
        self.inner.as_ref().map_or(0, |a| a.n_frames() as i64)
    }

    /// Normalized g(r) (one value per bin); empty before any accepted frame.
    pub fn finalize(&self) -> Vec<f64> {
        match self.inner.as_ref().map(|a| a.finalize()) {
            Some(Ok(res)) => res.rdf.to_vec(),
            _ => Vec::new(),
        }
    }
}

/// Streaming MSD accumulator — wraps molrs `compute::MSDAccumulator`
/// (Direct curve + windowed sums capped at `window` lags).
pub struct MsdAccumulator {
    inner: molrs::compute::MSDAccumulator,
}

/// Construct a streaming MSD accumulator resolving windowed lags up to
/// `window` frames (`<= 0` = Direct curve only; `diffusion` then returns NaN).
fn msd_accumulator_new(window: i64) -> Box<MsdAccumulator> {
    Box::new(MsdAccumulator {
        inner: molrs::compute::MSDAccumulator::new(window.max(0) as usize),
    })
}

impl MsdAccumulator {
    /// Fold one frame of blocked `x|y|z` positions (first frame = Direct-mode
    /// reference, latches the DOF count). `false` on a shape/DOF mismatch.
    pub fn accumulate(&mut self, positions: &[f64]) -> bool {
        self.inner.accumulate(positions).is_ok()
    }

    /// Number of accepted frames.
    pub fn n_frames(&self) -> i64 {
        self.inner.n_frames() as i64
    }

    /// Direct-mode MSD(t) curve (one value per accepted frame, index 0 = 0).
    pub fn direct_curve(&self) -> Vec<f64> {
        self.inner.direct_curve().to_vec()
    }

    /// Einstein D = LinearFit slope / (2·dims) over the windowed-MSD curve
    /// within `[fit_lo, fit_hi]` fractions of the max resolved lag. NaN on bad
    /// args, fewer than two frames, `window = 0`, or a fit error.
    pub fn diffusion(&self, dt: f64, dims: i32, fit_lo: f64, fit_hi: f64) -> f64 {
        use molrs::compute::{Fit, LinearFit};
        if dt <= 0.0 || dt.is_nan() || dims <= 0 {
            return f64::NAN;
        }
        let msd = self.inner.windowed_msd();
        if msd.len() < 2 {
            return f64::NAN;
        }
        let lag_times: Array1<f64> = (0..msd.len()).map(|i| i as f64 * dt).collect();
        let msd = Array1::from_vec(msd);
        match (LinearFit {
            window: (fit_lo, fit_hi),
        })
        .fit((&lag_times, &msd))
        {
            Ok(fit) => fit.slope / (2.0 * f64::from(dims)),
            Err(_) => f64::NAN,
        }
    }
}

/// Streaming DOF-averaged velocity-ACF accumulator — wraps molrs
/// `compute::VACFAccumulator`. `resolution < 1` leaves it inert.
pub struct VacfAccumulator {
    inner: Option<molrs::compute::VACFAccumulator>,
}

/// Construct a streaming VACF accumulator resolving lags `0..=resolution`.
fn vacf_accumulator_new(resolution: i64) -> Box<VacfAccumulator> {
    let inner = if resolution >= 1 {
        molrs::compute::VACFAccumulator::new(resolution as usize).ok()
    } else {
        None
    };
    Box::new(VacfAccumulator { inner })
}

impl VacfAccumulator {
    /// Fold one flat velocity frame (any fixed DOF count; Atomiverse feeds
    /// blocked `vx|vy|vz`). `false` on a DOF mismatch or empty frame.
    pub fn accumulate(&mut self, velocities: &[f64]) -> bool {
        self.inner
            .as_mut()
            .is_some_and(|a| a.accumulate(velocities).is_ok())
    }

    /// Number of accepted frames.
    pub fn n_frames(&self) -> i64 {
        self.inner.as_ref().map_or(0, |a| a.n_frames() as i64)
    }

    /// Mean-subtracted, DOF-averaged ACF for lags
    /// `0..=min(resolution, n_frames − 1)`; empty with fewer than two frames.
    pub fn finalize(&self) -> Vec<f64> {
        match self.inner.as_ref().map(|a| a.finalize()) {
            Some(Ok(curve)) => curve,
            _ => Vec::new(),
        }
    }
}

// ── I/O ──────────────────────────────────────────────────────────────────────

/// Write one frame to an XYZ file (standard element+coords).
///
/// `append=false` truncates (create); `append=true` appends the frame. (The
/// previous `_ext` variants were plain aliases — there is no extended-column
/// output today, so this is the single writer.)
fn write_frame_xyz(
    path: &str,
    type_id: &[i32],
    x: &[f64],
    y: &[f64],
    z: &[f64],
    box_mat: &[f64],
    append: bool,
) {
    let frame = frame_with_elements(type_id, x, y, z, box_mat);
    write_xyz_path(path, &frame, append).expect("write_frame_xyz");
}

fn write_xyz_path(path: &str, frame: &Frame, append: bool) -> Result<(), String> {
    let f = if append {
        OpenOptions::new()
            .create(true)
            .append(true)
            .open(path)
            .map_err(|err| format!("open {path}: {err}"))?
    } else {
        File::create(path).map_err(|err| format!("create {path}: {err}"))?
    };
    let mut w = BufWriter::new(f);
    write_xyz_frame(&mut w, frame).map_err(|err| err.to_string())
}

/// Write one frame with exact-dtype metadata.
#[allow(clippy::too_many_arguments)]
fn write_frame_xyz_typed(
    path: &str,
    type_id: &[i32],
    x: &[f64],
    y: &[f64],
    z: &[f64],
    box_mat: &[f64],
    meta: Vec<bridge::ffi::MetaEntry>,
    append: bool,
) -> Result<(), String> {
    let mut frame = frame_with_elements(type_id, x, y, z, box_mat);
    for entry in meta {
        let (key, value) = meta_from_entry(entry)?;
        frame.meta.insert(key, value);
    }
    write_xyz_path(path, &frame, append)
}

/// Write one frame (+ named per-atom fields) to a single-frame Zarr store.
///
/// Builds a transient `Frame` (element+x/y/z + simbox + one column per
/// `field_names[i]` from `field_data` reshaped `[n_fields, n_atoms]`), wraps it
/// as a single-frame `Trajectory`, and persists via `write_trajectory_file`.
/// Replaces the old per-record Zarr writer (Atomiverse's polyethylene checkpoint).
#[cfg(feature = "zarr")]
#[allow(clippy::too_many_arguments)]
fn write_frame_zarr(
    path: &str,
    type_id: &[i32],
    x: &[f64],
    y: &[f64],
    z: &[f64],
    box_mat: &[f64],
    field_names: Vec<String>,
    field_data: &[f64],
) {
    let n = type_id.len();
    let mut frame = frame_with_elements(type_id, x, y, z, box_mat);
    if let Some(atoms) = frame.get_mut("atoms") {
        for (fi, name) in field_names.iter().enumerate() {
            let base = fi * n;
            if base + n <= field_data.len() {
                atoms
                    .insert(
                        name.as_str(),
                        Array1::from_vec(field_data[base..base + n].to_vec()).into_dyn(),
                    )
                    .unwrap();
            }
        }
    }
    let traj = Trajectory::from_frames(vec![frame]);
    write_trajectory_file(path, &traj).expect("write_frame_zarr: write");
}

/// Read the first frame of a Zarr store into a fresh `FrameRef`.
///
/// Used by Atomiverse checkpoint reload (`cpu::ZarrReader`): stage 1 of a long
/// bench writes its end-state via [`write_frame_zarr`], then later debug
/// iterations call this to skip stage 1. The returned `FrameRef` is populated
/// via `with_mut` on a fresh standalone store — readers (`frame_column_f64`,
/// `frame_box`, etc.) see exactly the columns and simbox that were stored.
#[cfg(feature = "zarr")]
fn read_frame_zarr_first(path: &str) -> Box<FrameRef> {
    let traj = read_trajectory_file(path).expect("read_frame_zarr_first: read");
    let frame = traj
        .frames
        .into_iter()
        .next()
        .expect("read_frame_zarr_first: empty trajectory");
    let inner = molrs_ffi::FrameRef::new_standalone();
    inner
        .with_mut(|f| {
            *f = frame;
        })
        .expect("read_frame_zarr_first: populate");
    Box::new(FrameRef(inner))
}

/// Atomic number for a chemical symbol — inverse of [`symbol_for_z`].
///
/// Delegates to molrs' canonical periodic table. No fallback: panics on an
/// unrecognized symbol, matching Atomiverse's explicit-error convention.
fn z_for_symbol(sym: &str) -> i32 {
    Element::by_symbol(sym)
        .map(|element| i32::from(element.z()))
        .unwrap_or_else(|| panic!("z_for_symbol: unknown element symbol '{sym}'"))
}

/// Read the first frame of an (ext)XYZ file into a materialize-ready `FrameRef`.
///
/// All parsing (atom table, `Lattice="..."` -> simbox) is done by the molrs
/// core ExtXYZ reader. The ExtXYZ `species` column is consumed and replaced by
/// the exchange-schema `type` (atomic number Z) i32 column, so the result
/// satisfies the exact schema that `cpu::materialize` requires
/// (`atoms.{x,y,z,type}`). The external-format column does not cross that
/// boundary.
fn xyz_read_first_frame(path: &str) -> Box<FrameRef> {
    let mut frame = molrs::io::data::xyz::read_xyz_frame(path).expect("xyz_read_first_frame: read");
    let atoms = frame
        .get_mut("atoms")
        .expect("xyz_read_first_frame: frame has no atoms block");
    let species = atoms
        .get_string("species")
        .expect("xyz_read_first_frame: atoms block has no ExtXYZ species column");
    let zs: Vec<i32> = species.iter().map(|symbol| z_for_symbol(symbol)).collect();
    atoms
        .insert("type", Array1::from_vec(zs).into_dyn())
        .expect("xyz_read_first_frame: insert atoms.type");
    atoms.remove("species");

    let inner = molrs_ffi::FrameRef::new_standalone();
    inner
        .with_mut(|f| {
            *f = frame;
        })
        .expect("xyz_read_first_frame: populate");
    Box::new(FrameRef(inner))
}

// ── Frame bridge ─────────────────────────────────────────────────────────────
//
// `molrs_ffi::FrameRef` is the handle type used by every molrs language
// binding (python, wasm). It pairs a `FrameId` with a shared `Store`
// (`Rc<RefCell<Store>>`) — cloning is two `Rc` bumps and keeps the `Store`
// alive. Atomiverse C++ reads/writes a `molrs.Frame` entirely through this
// handle, so the SCF / MD pipeline never copies a whole frame.
//
// cxx `extern "Rust"` opaque types are crate-local by convention, so the
// bridged type is a thin newtype around `molrs_ffi::FrameRef` rather than a
// re-export. All `frame_*` functions deref through `.0`.

/// CXX-bridged opaque handle to a `molrs.Frame`.
///
/// Newtype around [`molrs_ffi::FrameRef`]; the inner handle carries the
/// shared `Store`, so cloning this and round-tripping it through a
/// `Box`/raw-pointer (e.g. a Python `PyCapsule`) keeps the same underlying
/// frame data — mutations through one handle are visible through all clones.
///
/// `#[repr(transparent)]` guarantees this newtype has exactly the layout of
/// the wrapped `molrs_ffi::FrameRef`, so a `*const molrs_ffi::FrameRef` (e.g.
/// the pointer carried by molrs-python's `_ffi_frameref_capsule`) and a
/// `*const FrameRef` are layout-compatible. `frame_clone_from_addr` relies on
/// this only as a defensive guarantee — it still dereferences the pointer as
/// the *real* `molrs_ffi::FrameRef` type, never as a layout cast.
#[repr(transparent)]
pub struct FrameRef(pub molrs_ffi::FrameRef);

/// Exact frame schema implemented by this bridge.
fn frame_schema_version() -> u32 {
    molrs::store::frame::FRAME_SCHEMA_VERSION
}

/// Create a fresh standalone frame (new `Store` + empty `Frame`).
///
/// @return boxed opaque handle owning a fresh shared store
fn frame_new() -> Box<FrameRef> {
    Box::new(FrameRef(molrs_ffi::FrameRef::new_standalone()))
}

/// Clone a `molrs_ffi::FrameRef` reachable through a `molrs.FrameRef`
/// PyCapsule address into a bridge-side [`FrameRef`] handle.
///
/// This is the cross-extension ingress point. molrs-python's
/// `Frame._ffi_frameref_capsule()` produces a `PyCapsule` named
/// `"molrs.FrameRef"`. PyO3 heap-boxes the capsule payload, and that payload
/// is a `#[repr(transparent)]` `FrameRefPtr` — itself a `*mut FrameRef`
/// (a clone of the Python frame's handle). The capsule's `void*` is
/// therefore `*mut *mut molrs_ffi::FrameRef`.
///
/// `addr` is `PyCapsule_GetPointer` cast to `usize`. This function resolves
/// it as `*const *const molrs_ffi::FrameRef`, dereferences once to reach the
/// cloned `*const FrameRef`, then `.clone()`s it — two cheap `Rc` bumps —
/// producing a handle onto the *same* shared `Store`. Reads and writes
/// through the returned handle are visible in the originating Python
/// `molrs.Frame`.
///
/// # Safety
///
/// `addr` must be the pointer returned by `PyCapsule_GetPointer` on a
/// `"molrs.FrameRef"` capsule from `molrs.Frame._ffi_frameref_capsule()`,
/// valid for the duration of this call. The molrs FFI store is
/// single-threaded and GIL-guarded; the caller must hold the GIL (or
/// otherwise guarantee exclusive access) while calling.
///
/// @param addr `molrs.FrameRef` capsule pointer (a `*mut *mut FrameRef`)
/// @return boxed bridge handle sharing the same store as the source frame
unsafe fn frame_clone_from_addr(addr: usize) -> Box<FrameRef> {
    let pp = addr as *const *const molrs_ffi::FrameRef;
    let p = unsafe { *pp };
    let cloned = unsafe { (*p).clone() };
    Box::new(FrameRef(cloned))
}

